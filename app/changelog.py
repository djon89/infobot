VERSION = CHANGES[0][0]


def _key(v: str) -> tuple[int, ...]:
    return tuple(int(x) for x in v.split("."))


def changes_since(last: str | None) -> list[tuple[str, str, list[str]]]:
    """Записи новее last. Если бот ещё ничего не объявлял — только последняя версия."""
    if last is None:
        return CHANGES[:1]
    try:
        lk = _key(last)
    except ValueError:
        return CHANGES[:1]
    return [c for c in CHANGES if _key(c[0]) > lk]


def announcement(entries) -> str:
    import html
    v, date = entries[0][0], entries[0][1]
    d = f"{date[8:10]}.{date[5:7]}.{date[:4]}"
    out = [f"🔄 <b>Бот обновлён до версии {v}</b> ({d})", ""]
    for ver, _, items in entries:
        if len(entries) > 1:
            out.append(f"<b>{ver}</b>")
        out += [f"• {html.escape(i)}" for i in items]
        out.append("")
    out.append("Все команды — /help")
    return "\n".join(out).strip()
